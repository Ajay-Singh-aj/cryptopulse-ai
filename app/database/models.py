
def create_tables(connection) -> None:
    """Create CryptoPulse AI database tables."""

    is_postgres = connection.__class__.__module__.startswith("psycopg")

    if is_postgres:
        statements = [
            """
            CREATE TABLE IF NOT EXISTS subscribers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                name TEXT,
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                preferred_topics TEXT DEFAULT '[]',
                receive_research_papers BOOLEAN NOT NULL DEFAULT TRUE,
                receive_industry_news BOOLEAN NOT NULL DEFAULT TRUE,
                subscribed_at TIMESTAMPTZ NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS newsletters (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                issue_id TEXT NOT NULL UNIQUE,
                title TEXT NOT NULL,
                issue_date DATE NOT NULL,
                generated_at TIMESTAMPTZ NOT NULL,
                introduction TEXT,
                total_articles INTEGER NOT NULL DEFAULT 0,
                status TEXT NOT NULL DEFAULT 'draft',
                html_content TEXT
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS newsletter_deliveries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                newsletter_id BIGINT NOT NULL REFERENCES newsletters(id),
                subscriber_id BIGINT NOT NULL REFERENCES subscribers(id),
                sent_at TIMESTAMPTZ,
                status TEXT NOT NULL DEFAULT 'pending',
                error_message TEXT,
                UNIQUE (newsletter_id, subscriber_id)
            )
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_subscribers_active
            ON subscribers(is_active)
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_newsletters_issue_date
            ON newsletters(issue_date)
            """,
        ]

        with connection.cursor() as cursor:
            for statement in statements:
                cursor.execute(statement)

    else:
        connection.executescript("""
            CREATE TABLE IF NOT EXISTS subscribers (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                email TEXT NOT NULL UNIQUE,
                name TEXT,
                is_active INTEGER NOT NULL DEFAULT 1,
                preferred_topics TEXT DEFAULT '[]',
                receive_research_papers INTEGER NOT NULL DEFAULT 1,
                receive_industry_news INTEGER NOT NULL DEFAULT 1,
                subscribed_at TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS newsletters (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                issue_id TEXT NOT NULL UNIQUE,
                title TEXT NOT NULL,
                issue_date TEXT NOT NULL,
                generated_at TEXT NOT NULL,
                introduction TEXT,
                total_articles INTEGER NOT NULL DEFAULT 0,
                status TEXT NOT NULL DEFAULT 'draft',
                html_content TEXT
            );

            CREATE TABLE IF NOT EXISTS newsletter_deliveries (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                newsletter_id INTEGER NOT NULL,
                subscriber_id INTEGER NOT NULL,
                sent_at TEXT,
                status TEXT NOT NULL DEFAULT 'pending',
                error_message TEXT,
                FOREIGN KEY (newsletter_id) REFERENCES newsletters(id),
                FOREIGN KEY (subscriber_id) REFERENCES subscribers(id),
                UNIQUE (newsletter_id, subscriber_id)
            );

            CREATE INDEX IF NOT EXISTS idx_subscribers_active
            ON subscribers(is_active);

            CREATE INDEX IF NOT EXISTS idx_newsletters_issue_date
            ON newsletters(issue_date);
        """)

    connection.commit()
